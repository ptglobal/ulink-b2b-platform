/** Resolve province code (hỗ trợ cả code cũ cho backward compat) */
export function resolveProvinceCode(code: string): string {
  return PROVINCE_MIGRATION[code] ?? code;
}

/** Tìm tên tỉnh — hỗ trợ cả code cũ */
export function getProvinceName(code: string): string | undefined {
  const resolved = resolveProvinceCode(code);
  return PROVINCES.find((p) => p.code === resolved)?.name;
}

